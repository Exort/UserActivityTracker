using UserActivityTracker.Services;
using UserActivityTracker.Utils;
using UserActivityTrackerTests.Helpers;

namespace UserActivityTrackerTests.Tests
{
    public class UserServiceTests
    {
        [Fact]
        public async Task Can_Create_User_Successfully()
        {
            TextDBContextScope dbContextScope = new TextDBContextScope();
            var userService = new UserService(dbContextScope.DbContext);

            var newUser = await userService.CreateUserAsync("UserName", "Jane", "Doe", PasswordUtils.GetSaltedPassword("password"));

            Assert.True(newUser.Id > 0, "User ID should be auto-generated by SQLite.");

            var retrievedUser = await userService.GetUserByIdAsync(newUser.Id);

            Assert.NotNull(retrievedUser);
            Assert.Equal(newUser.UserName, retrievedUser.UserName);
            Assert.Equal(newUser.FirstName, retrievedUser.FirstName);
            Assert.Equal(newUser.LastName, retrievedUser.LastName);
            Assert.Equal(newUser.SaltedPassword, retrievedUser.SaltedPassword);
        }

        [Fact]
        public async Task CreateUser_Throws_OnInvalidInput()
        {
            TextDBContextScope dbContextScope = new TextDBContextScope();
            var userService = new UserService(dbContextScope.DbContext);

            await Assert.ThrowsAsync<ArgumentException>(async () =>
                await userService.CreateUserAsync("", "", "", ""));
        }

        [Fact]
        public async Task GetUserById_ReturnsNull_WhenNotFound()
        {
            TextDBContextScope dbContextScope = new TextDBContextScope();
            var userService = new UserService(dbContextScope.DbContext);

            var result = await userService.GetUserByIdAsync(9999);
            Assert.Null(result);
        }

        [Fact]
        public async Task DeleteUserById_ReturnsFalse_WhenNotFound()
        {
            TextDBContextScope dbContextScope = new TextDBContextScope();
            var userService = new UserService(dbContextScope.DbContext);

            var result = await userService.DeleteUserByIdAsync(9999);
            Assert.False(result);
        }

        [Fact]
        public async Task DeleteUserById_Succeeds_ForDifferentUser()
        {
            TextDBContextScope dbContextScope = new TextDBContextScope();
            var userService = new UserService(dbContextScope.DbContext);

            var user1 = await userService.CreateUserAsync("u1", "First1", "Last1", "password");
            var user2 = await userService.CreateUserAsync("u2", "First2", "Last2", "password");

            var deleted = await userService.DeleteUserByIdAsync(user1.Id);
            Assert.True(deleted);

            var shouldBeNull = await userService.GetUserByIdAsync(user1.Id);
            Assert.Null(shouldBeNull);

            var remaining = await userService.GetUserByIdAsync(user2.Id);
            Assert.NotNull(remaining);
        }

        [Fact]
        public async Task GetAllUsers_ReturnsAll()
        {
            TextDBContextScope dbContextScope = new TextDBContextScope();
            var userService = new UserService(dbContextScope.DbContext);

            await userService.CreateUserAsync("u1", "A", "Z", "password");
            await userService.CreateUserAsync("u2", "B", "Y", "password");

            var all = await userService.GetAllUsersAsync();
            Assert.Equal(2, all.Count);
        }

        [Fact]
        public async Task UpdateUser_UpdatesFields()
        {
            TextDBContextScope dbContextScope = new TextDBContextScope();
            var userService = new UserService(dbContextScope.DbContext);

            var user = await userService.CreateUserAsync("u1", "OldFirst", "OldLast", "password");
            user.FirstName = "NewFirst";
            await userService.UpdateUserAsync(user);

            var updated = (await userService.GetUserByIdAsync(user.Id))!; //assume not null as this is covered by another test
            Assert.Equal("NewFirst", updated.FirstName);
        }

        [Fact]
        public async Task SearchUsers_FindsByFirstOrLastName_AndEmptyReturnsAll()
        {
            TextDBContextScope dbContextScope = new TextDBContextScope();
            var userService = new UserService(dbContextScope.DbContext);

            await userService.CreateUserAsync("u1", "Anna", "Smith", "password");
            await userService.CreateUserAsync("u2", "Bob", "Johnson", "password");

            var found = await userService.SearchUsersAsync("ann");
            Assert.Single(found);

            var all = await userService.SearchUsersAsync("");
            Assert.Equal(2, all.Count);
        }
    }
}